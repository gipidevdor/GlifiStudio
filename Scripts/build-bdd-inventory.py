"""Inventory the pinned upstream generator's expanded Swift, without parsing Gherkin."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import runpy
import sys
from pathlib import Path
from tempfile import TemporaryDirectory


ROOT = Path(__file__).resolve().parent.parent
FEATURES = ROOT / "Packages/GlifiCore/Tests/GlifiBDDTests/Features"
MARKER = "// Generated by CucumberSwiftTestingPlugin from this target's feature files. Do not edit."
GENERATOR = {
    "package": "CucumberSwift", "version": "6.9.0",
    "revision": "5547f9025c0da3f0276a22a3c746bfebc405741f",
    "source": "Sources/CucumberSwiftTestingGenerator/SwiftTestingSource.swift",
    "parser": "Sources/CucumberSwiftGherkin/FeatureFile.swift",
}
LITERAL = r'"(?:\\.|[^"\\\n])*"'


def swift_string(literal: str) -> str:
    """Decode only the string escapes emitted by the reviewed generator's literal()."""
    if not literal.startswith('"') or not literal.endswith('"'):
        raise ValueError("literal Swift non valido")
    result = []
    i = 1
    while i < len(literal) - 1:
        char = literal[i]
        i += 1
        if char != "\\":
            result.append(char)
            continue
        if i >= len(literal) - 1:
            raise ValueError("escape Swift incompleto")
        escape = literal[i]
        i += 1
        if escape in {'\\': '\\', '"': '"', 'n': '\n', 'r': '\r', 't': '\t'}:
            result.append({'\\': '\\', '"': '"', 'n': '\n', 'r': '\r', 't': '\t'}[escape])
        elif escape == "u" and i < len(literal) and literal[i] == "{":
            end = literal.find("}", i)
            if end < 0 or not re.fullmatch(r"[0-9a-fA-F]{1,8}", literal[i + 1:end]):
                raise ValueError("scalare Swift non valido")
            scalar = int(literal[i + 1:end], 16)
            if scalar > 0x10FFFF or 0xD800 <= scalar <= 0xDFFF:
                raise ValueError("scalare Swift fuori dominio")
            result.append(chr(scalar))
            i = end + 1
        else:
            raise ValueError("escape non emesso dal generatore pinned")
    return "".join(result)


def expanded_cases(source: str, feature_directory: Path) -> list[dict]:
    if not source.startswith(MARKER):
        raise ValueError("header del generatore upstream non riconosciuto")
    problems = re.search(
        r"^private func cucumberGherkinProblems\(\) \{\n(.*?)^\}", source, re.M | re.S)
    if problems is None or problems.group(1).strip():
        raise ValueError("problemi Gherkin o formato del generatore non riconosciuto")
    starts = list(re.finditer(
        r"^[ \t]*(?:private let cucumber[A-Za-z0-9_]+ = )?"
        r"CucumberSwiftTesting\.GherkinScenario\(\n", source, re.M))
    if not starts:
        raise ValueError("generatore senza scenari espansi")
    cases = []
    seen = set()
    for index, start in enumerate(starts):
        block = source[start.end():starts[index + 1].start() if index + 1 < len(starts) else len(source)]
        header, separator, body = block.partition("steps: [\n")
        if not separator:
            raise ValueError("scenario privo di passaggi generati")
        file = re.search(r"^\s*file: (" + LITERAL + r"),$", header, re.M)
        line = re.search(r"^\s*line: ([1-9][0-9]*),$", header, re.M)
        title = re.search(r"^\s*title: (" + LITERAL + r"),$", header, re.M)
        if file is None or line is None or title is None:
            raise ValueError("intestazione scenario generato non riconosciuta")
        path = Path(swift_string(file.group(1))).resolve()
        if path.parent != feature_directory.resolve() or not path.is_file():
            raise ValueError("scenario riferito a una feature esterna o assente")
        identity = path.name, int(line.group(1))
        if identity in seen:
            raise ValueError("posizione espansa duplicata")
        seen.add(identity)
        step_starts = list(re.finditer(r"^\s*CucumberSwiftTesting\.GherkinStep\(\n", body, re.M))
        texts = []
        metadata = []
        for step_index, step_start in enumerate(step_starts):
            end = step_starts[step_index + 1].start() if step_index + 1 < len(step_starts) else len(body)
            step = body[step_start.end():end]
            text = re.search(r"^\s*text: (" + LITERAL + r"),$", step, re.M)
            keyword = re.search(r"^\s*keywordName: (" + LITERAL + r"),$", step, re.M)
            location = re.search(r"^\s*line: ([1-9][0-9]*)(?:,|\))$", step, re.M)
            if text is None or keyword is None or location is None:
                raise ValueError("metadati del passaggio generato non riconosciuti")
            texts.append(swift_string(text.group(1)))
            metadata.append({"line": int(location.group(1)),
                             "keyword": swift_string(keyword.group(1)), "name": texts[-1]})
        if not texts:
            raise ValueError("scenario espanso senza passaggi")
        tags = []
        for field in ("featureTags", "tags"):
            encoded = re.search(r"^\s*" + field + r": (\[[^\n]*\]),$", header, re.M)
            if encoded is not None:
                tags.extend(swift_string(x) for x in re.findall(LITERAL, encoded.group(1)))
        cases.append({"feature": identity[0], "line": identity[1],
                      "title": swift_string(title.group(1)), "tags": tags, "stepTexts": texts,
                      "stepMetadata": metadata})
    actual = {p.name for p in feature_directory.glob("*.feature")}
    if {x["feature"] for x in cases} != actual:
        raise ValueError("il generatore non contiene esattamente tutte le feature")
    return cases


def inventory(cases: list[dict], directory: Path) -> dict:
    checker = runpy.run_path(str(ROOT / "Scripts/check-bdd.py"))
    step_digest = checker["step_metadata_digest"]
    features = []
    for name in sorted({x["feature"] for x in cases}):
        scenarios = sorted((x for x in cases if x["feature"] == name), key=lambda x: x["line"])
        features.append({"file": name, "expandedScenarios": len(scenarios),
                         "sourceSHA256": hashlib.sha256((directory / name).read_bytes()).hexdigest(),
                         "scenarios": [{"line": x["line"], "stepCount": len(x["stepTexts"]),
                                        "stepsSHA256": step_digest(x["stepMetadata"])}
                                       for x in scenarios]})
    return {"schema": "studio.glifi.bdd-coverage", "schemaVersion": 2,
            "features": features}


def self_test() -> None:
    if not __debug__:
        raise ValueError("il self-test richiede Python senza ottimizzazione degli assert")
    assert swift_string(r'"a\n\"b\\u{7f}\u{7f}"') == 'a\n"b\\u{7f}\x7f'
    for literal in [r'"\u{D800}"', r'"\u{110000}"', r'"\q"']:
        try:
            swift_string(literal)
        except ValueError:
            pass
        else:
            raise AssertionError("escape estraneo al producer accettato")
    with TemporaryDirectory(prefix="GlifiBDDGenerator-") as temporary:
        root = Path(temporary)
        directory = root / "Packages/GlifiCore/Tests/GlifiBDDTests/Features"
        directory.mkdir(parents=True)
        feature = directory / "Synthetic.feature"
        feature.write_text("# language: it\n", encoding="utf-8")
        scenario = (
            '    CucumberSwiftTesting.GherkinScenario(\n'
            '        title: "Synthetic",\n'
            f'        file: {json.dumps(str(feature))},\n'
            '        line: 4,\n        steps: [\n'
            '            CucumberSwiftTesting.GherkinStep(\n'
            '                keyword: [.then],\n'
            '                keywordName: "Allora",\n'
            '                text: "literal CucumberSwiftTesting.GherkinStep(\\n",\n'
            '                line: 5)\n        ])\n')
        source = MARKER + '\nprivate func cucumberGherkinProblems() {\n}\n' + scenario
        cases = expanded_cases(source, directory)
        assert len(cases) == 1 and len(cases[0]["stepTexts"]) == 1
        result = inventory(cases, directory)
        assert result["schemaVersion"] == 2
        scenario_entry = result["features"][0]["scenarios"][0]
        assert scenario_entry["line"] == 4 and scenario_entry["stepCount"] == 1
        assert re.fullmatch(r"[0-9a-f]{64}", scenario_entry["stepsSHA256"])
        assert cases[0]["stepMetadata"] == [{"line": 5, "keyword": "Allora",
                                             "name": "literal CucumberSwiftTesting.GherkinStep(\n"}]
        checker = runpy.run_path(str(ROOT / "Scripts/check-bdd.py"))

        standalone = scenario.replace(
            '    CucumberSwiftTesting.GherkinScenario(',
            'private let cucumberScenario2 = CucumberSwiftTesting.GherkinScenario(', 1)
        standalone = standalone.replace('line: 4,', 'line: 8,')
        mixed = expanded_cases(source + standalone, directory)
        assert [x['line'] for x in mixed] == [4, 8]
        assert [len(x['stepTexts']) for x in mixed] == [1, 1]
        for invalid in [source + scenario, source.replace("line: 4,", "line: 0,"),
                        source.replace("cucumberGherkinProblems()", "unknown()"),
                        source.replace("\n}\n", '\n Issue.record("bad")\n}\n'),
                        source.replace('keywordName: "Allora",', 'keywordName: 1,'),
                        source.replace('line: 5)', 'line: 0)')]:
            try:
                expanded_cases(invalid, directory)
            except ValueError:
                pass
            else:
                raise AssertionError("output incompleto o non valido del generatore accettato")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--generated-source", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--cases-output", type=Path)
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    try:
        if args.self_test:
            self_test()
        if args.generated_source is None:
            if not args.self_test or args.output or args.cases_output:
                parser.error("--generated-source richiesto per scrivere inventari")
            return 0
        if args.output is None:
            parser.error("--output richiesto")
        cases = expanded_cases(args.generated_source.read_text(), FEATURES)
        result = inventory(cases, FEATURES)
        args.output.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n")
        if args.cases_output:
            args.cases_output.write_text(json.dumps(cases, ensure_ascii=False, indent=2) + "\n")
        print(f"Inventario upstream: {len(result['features'])} feature, {len(cases)} scenari espansi")
        return 0
    except (OSError, ValueError, AssertionError) as error:
        print(f"Inventario BDD non generato: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
